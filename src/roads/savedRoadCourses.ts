export type CourseKind = "rural" | "motorway";

export function savedCourseArea(kind: CourseKind): RoadArea {
  const rural = kind === "rural";
  const roads = rural ? RURAL_COURSE_ROADS : MOTORWAY_COURSE_ROADS;
  return {
    center: rural ? RURAL_COURSE_CENTER : MOTORWAY_COURSE_CENTER,
    radiusMeters: rural ? 800 : 1700,
    roads,
    matched: roads.length,
    truncated: false,
    omitted: [],
    signals: [],
    signs: COURSE_SIGNS[kind] ?? [],
    source: "saved-openstreetmap",
  };
}

/** The long on-ramp that joins Arlandaleden. */
export const MOTORWAY_RAMP_WAY_ID = "4236358";
/** Färentunavägen, the 70 km/h two-lane section. */
export const RURAL_WAY_ID = "105180756";

/** A start on the saved course. The edge id comes from the road network, not a guessed coordinate. */
export function courseStart(
  roads: readonly RoadSegment[],
  kind: CourseKind,
): { edgeId: string; distanceMeters: number } | null {
  const network = buildRoadNetwork([...roads]);
  if (kind === "rural") {
    const edge = network.edges
      .filter((item) => item.osmWayId === RURAL_WAY_ID && item.id.endsWith(":forward"))
      .sort((left, right) => right.lengthMeters - left.lengthMeters)[0];
    if (!edge) {
      return null;
    }
    return { edgeId: edge.id, distanceMeters: Math.min(18, Math.max(6, edge.lengthMeters * 0.02)) };
  }
  const way = roads.find((road) => road.osmWayId === MOTORWAY_RAMP_WAY_ID);
  const first = way?.coordinates[0];
  const edges = network.edges.filter((item) => item.osmWayId === MOTORWAY_RAMP_WAY_ID);
  const edge =
    edges.find(
      (item) =>
        first &&
        Math.abs(item.points[0]!.lat - first.lat) < 1e-5 &&
        Math.abs(item.points[0]!.lng - first.lng) < 1e-5,
    ) ?? edges[0];
  if (!edge) {
    return null;
  }
  return { edgeId: edge.id, distanceMeters: Math.min(20, Math.max(8, edge.lengthMeters * 0.03)) };
}
